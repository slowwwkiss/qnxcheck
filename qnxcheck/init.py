"""`qnxcheck init` — generate a correct QNX 8.0 project skeleton.

The generated project is deliberately small and deliberately correct:
its buildfile passes `qnxcheck buildfile`, its C source passes
`qnxcheck c`, and its Makefile passes `qnxcheck makefile` (dogfooding).
Two targets are supported: x86_64 QEMU and aarch64 Raspberry Pi 5.
"""

from __future__ import annotations

import os

HELLO_C = '''/* hello.c — minimal correct QNX Neutrino message-passing server.
 *
 * Listens on the name "hello": a client sends any message and gets the
 * reply "hello from QNX". Written to pass `qnxcheck c`:
 *  - <sys/neutrino.h> is included (C01)
 *  - name_attach() result is checked, name_detach() is paired (C05)
 *  - every MsgReceive() path ends in MsgReply() or MsgError() (C13)
 *  - no fork(), no Linux-only APIs, no blocking MsgSend() (C06/C11/C12)
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <errno.h>
#include <sys/neutrino.h>

int main(void) {
    name_attach_t *attach;
    int rcvid;
    char msg[256];
    const char reply[] = "hello from QNX";

    attach = name_attach(NULL, "hello", 0);
    if (attach == NULL) {
        fprintf(stderr, "name_attach failed: %s\\n", strerror(errno));
        return EXIT_FAILURE;
    }

    for (;;) {
        rcvid = MsgReceive(attach->chid, msg, sizeof(msg), NULL);
        if (rcvid == -1) {
            break; /* channel closed or error: shut down cleanly */
        }
        if (rcvid == 0) {
            continue; /* a pulse, not a message: keep waiting */
        }
        if (MsgReply(rcvid, EOK, reply, strlen(reply) + 1) == -1) {
            break;
        }
    }

    name_detach(attach, 0);
    return EXIT_SUCCESS;
}
'''

MAKEFILE = '''# Makefile — QNX 8.0 recursive makefile for the hello project.
# Build on the host with the QNX SDP 8.0 toolchain (qcc/make):
#   make            # builds for $(TARGET_CPU)
#   make install    # installs into $(INSTALLDIR)
TARGET_CPU = {cpu}
USEFILE = $(PROJECT_ROOT)/usage.txt
INSTALLDIR = usr/bin
EXTRA_CCOPTS += -Wall -Wextra

include $(QNX_TARGET)/usr/include/mk/common.mk
'''

USAGE_TXT = '''hello — minimal QNX Neutrino message-passing server.
Listens on the name "hello" and replies "hello from QNX" to any message.
'''

README_SKELETON = '''# {name} — QNX 8.0 project skeleton

Generated by `qnxcheck init`. Target: {target_desc}.

## What is in here

- `system.build` — mkifs buildfile for a QNX 8.0 OS image. It boots the
  kernel on {target_desc} and starts `hello`.
- `src/hello.c` — a minimal, correct QNX Neutrino server (name_attach +
  MsgReceive/MsgReply loop). It passes `qnxcheck c` cleanly.
- `Makefile` — QNX recursive makefile (common.mk, TARGET_CPU, USEFILE,
  INSTALLDIR). It passes `qnxcheck makefile` cleanly.

## Build (needs QNX SDP 8.0, free via QNX Everywhere)

    make                 # cross-compile hello for {cpu}
    mkifs system.build system.ifs   # build the bootable OS image

## Run

- x86_64: `qemu-system-x86_64 -kernel system.ifs -serial stdio`
- aarch64: boot `system.ifs` on a Raspberry Pi 5 (see QNX docs).

## Validate (no QNX toolchain needed — runs on the Linux host)

    qnxcheck check .
'''

BUILDFILE_X86_64 = '''# system.build — QNX 8.0 OS image for x86_64 QEMU.
# Build with: mkifs system.build system.ifs
[image=0x400000]
[virtual=x86_64,multiboot] boot = {
    startup-x86 -D 8250
    PATH=/proc/boot procnto-smp-instr
}
[+script] .script = {
    display_msg "Hello from QNX 8.0"
    procmgr_symlink ../../proc/boot/libc.so.6 /usr/lib/ldqnx.so.2
    reopen
    hello &
}
[type=link] /usr/lib/ldqnx.so.2=/proc/boot/libc.so.6
libc.so.6
[uid=0 gid=0 perms=0755] /proc/boot/hello = hello
'''

BUILDFILE_RPI5 = '''# system.build — QNX 8.0 OS image for Raspberry Pi 5 (aarch64).
# Build with: mkifs system.build system.ifs
[image=0x800000]
[virtual=aarch64le,elf] boot = {
    startup-rpi4 -D 8250
    PATH=/proc/boot procnto-smp-instr
}
[+script] .script = {
    display_msg "Hello from QNX 8.0 on Raspberry Pi 5"
    procmgr_symlink ../../proc/boot/libc.so.6 /usr/lib/ldqnx.so.2
    reopen
    hello &
}
[type=link] /usr/lib/ldqnx.so.2=/proc/boot/libc.so.6
libc.so.6
[uid=0 gid=0 perms=0755] /proc/boot/hello = hello
'''

TARGETS = {
    "x86_64": {
        "cpu": "x86_64",
        "desc": "x86_64 QEMU (multiboot)",
        "buildfile": BUILDFILE_X86_64,
    },
    "rpi5": {
        "cpu": "aarch64le",
        "desc": "Raspberry Pi 5 (aarch64, ELF)",
        "buildfile": BUILDFILE_RPI5,
    },
}


def generate(target: str, name: str, out_dir: str) -> list[str]:
    """Write the skeleton into out_dir. Returns the list of files written."""
    if target not in TARGETS:
        raise ValueError(
            f"unknown target '{target}' (choose: "
            + ", ".join(sorted(TARGETS)) + ")")
    cfg = TARGETS[target]
    written = []

    def write(rel, content):
        full = os.path.join(out_dir, rel)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as fh:
            fh.write(content)
        written.append(rel)

    write("system.build", cfg["buildfile"])
    write("src/hello.c", HELLO_C)
    write("Makefile", MAKEFILE.format(cpu=cfg["cpu"]))
    write("usage.txt", USAGE_TXT)
    write("README.md", README_SKELETON.format(
        name=name, target_desc=cfg["desc"], cpu=cfg["cpu"]))
    return written
